function mix(color, weight, base = 'transparent') {
  return `color-mix(in srgb, ${color} ${weight}%, ${base})`;
}

function gradient(top, bottom) {
  return `linear-gradient(180deg, ${top} 0%, ${bottom} 100%)`;
}

function defaultShadow(tone) {
  return tone === 'dark'
    ? '0 14px 32px rgba(2, 6, 23, 0.34)'
    : '0 10px 28px rgba(15, 23, 42, 0.08)';
}

function buildMode(tone, shared, palette) {
  const isDark = tone === 'dark';
  const accent = palette.accent;
  const accentStrong = palette.accentStrong ?? accent;
  const info = palette.info ?? accent;
  const success = palette.success ?? (isDark ? '#4ade80' : '#15803d');
  const warning = palette.warning ?? (isDark ? '#f59e0b' : '#b45309');
  const danger = palette.danger ?? (isDark ? '#f87171' : '#b42318');
  const line = palette.line ?? mix(palette.text, isDark ? 18 : 10);
  const lineStrong = palette.lineStrong ?? mix(palette.text, isDark ? 28 : 18);
  const accentSoft = palette.accentSoft ?? mix(accent, isDark ? 14 : 8);
  const surfaceOverlay = palette.surfaceOverlay ?? palette.panel;
  const surfaceCard = palette.surfaceCard ?? palette.panel;
  const surfaceCardStrong = palette.surfaceCardStrong ?? palette.panelStrong;
  const surfaceInput = palette.surfaceInput ?? palette.panelStrong;
  const surfaceSubtle = palette.surfaceSubtle ?? palette.bgStrong;
  const surfaceMuted = palette.surfaceMuted ?? palette.bgStrong;
  const surfaceMutedSoft =
    palette.surfaceMutedSoft ?? mix(palette.bgStrong, isDark ? 66 : 90);
  const buttonPrimaryBackground = palette.buttonPrimaryBackground ?? palette.text;
  const buttonPrimaryText = palette.buttonPrimaryText ?? (isDark ? palette.bg : '#ffffff');
  const buttonPrimaryHoverBackground =
    palette.buttonPrimaryHoverBackground ?? accentStrong;
  const buttonPrimaryHoverBorder =
    palette.buttonPrimaryHoverBorder ?? buttonPrimaryHoverBackground;
  const shadow = palette.shadow ?? shared.shadow ?? defaultShadow(tone);
  const machineSurface = palette.machineSurface ?? surfaceOverlay;
  const machineNode = palette.machineNode ?? surfaceSubtle;
  const machineBranch = palette.machineBranch ?? surfaceOverlay;

  return {
    '--theme-font-body': shared.fontBody ?? FONT_STACKS.systemBody,
    '--theme-font-display': shared.fontDisplay ?? FONT_STACKS.systemDisplay,
    '--theme-font-mono': shared.fontMono ?? FONT_STACKS.mono,
    '--theme-font-weight-display': shared.fontWeightDisplay ?? '600',
    '--theme-letter-spacing-display': shared.displayTracking ?? '-0.02em',
    '--theme-letter-spacing-eyebrow': shared.eyebrowTracking ?? '0.1em',
    '--theme-border-width': shared.borderWidth ?? '1px',
    '--theme-border-width-strong': shared.borderWidthStrong ?? shared.borderWidth ?? '1px',
    '--theme-border-style': shared.borderStyle ?? 'solid',
    '--theme-radius-card': shared.radiusCard ?? '16px',
    '--theme-radius-control': shared.radiusControl ?? '12px',
    '--theme-radius-pill': shared.radiusPill ?? '999px',
    '--theme-bg': palette.bg,
    '--theme-bg-strong': palette.bgStrong,
    '--theme-panel': palette.panel,
    '--theme-panel-strong': palette.panelStrong,
    '--theme-line': line,
    '--theme-line-strong': lineStrong,
    '--theme-text': palette.text,
    '--theme-muted': palette.muted,
    '--theme-accent': accent,
    '--theme-accent-strong': accentStrong,
    '--theme-accent-soft': accentSoft,
    '--theme-blue-soft': palette.blueSoft ?? accentSoft,
    '--theme-success': success,
    '--theme-warning': warning,
    '--theme-danger': danger,
    '--theme-info': info,
    '--theme-shadow': shadow,
    '--theme-body-background':
      palette.bodyBackground ?? gradient(palette.bg, palette.bgStrong),
    '--theme-sidebar-background':
      palette.sidebarBackground ?? gradient(palette.panelStrong, palette.bgStrong),
    '--theme-nav-active-border':
      palette.navActiveBorder ?? mix(accent, isDark ? 22 : 18),
    '--theme-nav-active-background':
      palette.navActiveBackground ??
      gradient(mix(accent, isDark ? 14 : 8), surfaceCardStrong),
    '--theme-panel-elevated':
      palette.panelElevated ?? gradient(palette.panel, palette.panelStrong),
    '--theme-surface-overlay': surfaceOverlay,
    '--theme-surface-card': surfaceCard,
    '--theme-surface-card-strong': surfaceCardStrong,
    '--theme-surface-input': surfaceInput,
    '--theme-surface-subtle': surfaceSubtle,
    '--theme-surface-muted': surfaceMuted,
    '--theme-surface-muted-soft': surfaceMutedSoft,
    '--theme-surface-selected':
      palette.surfaceSelected ?? gradient(mix(accent, isDark ? 14 : 8), surfaceCardStrong),
    '--theme-badge-neutral': palette.badgeNeutral ?? mix(palette.text, isDark ? 14 : 6),
    '--theme-badge-neutral-text': palette.badgeNeutralText ?? palette.text,
    '--theme-badge-info': palette.badgeInfo ?? mix(info, isDark ? 18 : 10),
    '--theme-badge-success': palette.badgeSuccess ?? mix(success, isDark ? 16 : 8),
    '--theme-badge-warning': palette.badgeWarning ?? mix(warning, isDark ? 18 : 10),
    '--theme-badge-danger': palette.badgeDanger ?? mix(danger, isDark ? 18 : 8),
    '--theme-badge-muted': palette.badgeMuted ?? mix(palette.muted, isDark ? 16 : 10),
    '--theme-button-primary-background': buttonPrimaryBackground,
    '--theme-button-primary-border':
      palette.buttonPrimaryBorder ?? buttonPrimaryBackground,
    '--theme-button-primary-text': buttonPrimaryText,
    '--theme-button-primary-hover-background': buttonPrimaryHoverBackground,
    '--theme-button-primary-hover-border': buttonPrimaryHoverBorder,
    '--theme-meter-track': palette.meterTrack ?? mix(palette.text, isDark ? 18 : 8),
    '--theme-meter-fill':
      palette.meterFill ?? `linear-gradient(90deg, ${accentStrong}, ${accent})`,
    '--theme-timeline-dot-ring':
      palette.timelineDotRing ?? mix(accent, isDark ? 24 : 14),
    '--theme-code-border':
      palette.codeBorder ?? (isDark ? mix(palette.text, 22) : palette.text),
    '--theme-code-background':
      palette.codeBackground ?? (isDark ? '#020617' : '#0f172a'),
    '--theme-code-text': palette.codeText ?? '#e5e7eb',
    '--theme-info-border-soft': palette.infoBorderSoft ?? mix(info, isDark ? 24 : 18),
    '--theme-success-border-soft':
      palette.successBorderSoft ?? mix(success, isDark ? 24 : 22),
    '--theme-danger-border-soft':
      palette.dangerBorderSoft ?? mix(danger, isDark ? 24 : 24),
    '--theme-composer-background':
      palette.composerBackground ?? gradient(palette.panel, palette.panelStrong),
    '--theme-machine-surface': machineSurface,
    '--theme-machine-node': machineNode,
    '--theme-machine-node-current-border':
      palette.machineNodeCurrentBorder ?? mix(accent, isDark ? 32 : 30),
    '--theme-machine-node-current-background':
      palette.machineNodeCurrentBackground ??
      gradient(mix(accent, isDark ? 16 : 8), palette.panelStrong),
    '--theme-machine-node-current-shadow':
      palette.machineNodeCurrentShadow ?? shadow,
    '--theme-machine-node-visited-border':
      palette.machineNodeVisitedBorder ?? mix(accent, isDark ? 18 : 16),
    '--theme-machine-node-visited-background':
      palette.machineNodeVisitedBackground ??
      gradient(mix(accent, isDark ? 8 : 4), palette.panel),
    '--theme-machine-node-reachable-border':
      palette.machineNodeReachableBorder ?? mix(palette.text, 24),
    '--theme-machine-arrow': palette.machineArrow ?? mix(palette.text, isDark ? 16 : 12),
    '--theme-machine-arrow-head':
      palette.machineArrowHead ?? mix(palette.text, isDark ? 22 : 18),
    '--theme-machine-arrow-active':
      palette.machineArrowActive ?? mix(accent, isDark ? 52 : 50),
    '--theme-machine-arrow-active-head':
      palette.machineArrowActiveHead ?? mix(accent, isDark ? 74 : 70),
    '--theme-machine-branch': machineBranch,
    '--theme-machine-branch-active-border':
      palette.machineBranchActiveBorder ?? mix(accent, isDark ? 24 : 20),
    '--theme-machine-branch-active-background':
      palette.machineBranchActiveBackground ?? mix(accent, isDark ? 14 : 8),
    '--theme-theme-option-background':
      palette.themeOptionBackground ?? surfaceOverlay,
    '--theme-theme-option-selected-border':
      palette.themeOptionSelectedBorder ?? mix(accent, isDark ? 32 : 28),
    '--theme-theme-option-selected-shadow':
      palette.themeOptionSelectedShadow ??
      `inset 0 0 0 1px ${mix(accent, isDark ? 24 : 22)}`,
    '--theme-pulse': palette.pulse ?? mix(accent, 24),
    '--theme-pulse-fade': palette.pulseFade ?? 'transparent',
    '--theme-pulse-end': palette.pulseEnd ?? 'transparent',
  };
}

function buildPreset(spec) {
  return {
    id: spec.id,
    label: spec.label,
    description: spec.description,
    tokens: {
      light: buildMode('light', spec.shared ?? {}, spec.light),
      dark: buildMode('dark', spec.shared ?? {}, spec.dark),
    },
  };
}

